GAME_ID = "SCUS-97316"
HEAP = 0x0100_0000
DAG_NODE_SIZE = 0x100
GUARD_BASE = 0x0120_0000
GUARD_SIZE = 0x1200
CHARACTER = 0x0140_0000
INFOBOX = 0x0150_0000
STRING_TABLE = 0x0151_0000
STRING_BUFFERS = 0x0152_0000

_slot_data_cache: dict[tuple, dict[str, Any]] = {}


def make_slot_data(**options: Any) -> dict[str, Any]:
  """Slot data as the client would receive it from the server: generated by
  the world and JSON round-tripped, so tuples arrive as lists."""
  key = tuple(sorted(options.items()))
  if key not in _slot_data_cache:
    multiworld = setup_multiworld(Sly2World, options=options, seed=1)
    world = multiworld.worlds[1]
    _slot_data_cache[key] = json.loads(json.dumps(world.fill_slot_data()))
  return json.loads(json.dumps(_slot_data_cache[key]))


def set_location(
  pine: FakePine, addr: dict, episode: int, map_id: int,
  job: int = 0xffffffff
) -> None:
  pine.poke32(addr["world id"], episode)
  pine.poke32(addr["map id"], map_id)
  pine.poke32(addr["job id"], job)


def dag_node(index: int) -> int:
  return HEAP + index*DAG_NODE_SIZE


def build_dag(pine: FakePine, addr: dict, n: int = 128) -> None:
  """A DAG of `n` nodes chained through +0x20, all status 0, no parents."""
  pine.poke32(addr["DAG root"], dag_node(0))
  for i in range(n):
    pine.poke32(dag_node(i) + 0x20, dag_node(i+1) if i+1 < n else 0)


def set_job_status(pine: FakePine, index: int, status: int) -> None:
  pine.poke32(dag_node(index) + 0x54, status)


def job_status(pine: FakePine, index: int) -> int:
  return pine.peek32(dag_node(index) + 0x54)


def set_job_mission(pine: FakePine, index: int, mission: int) -> None:
  pine.poke32(dag_node(index) + 0x7c, mission)


def set_parents(pine: FakePine, index: int, parents: list[int]) -> None:
  node = dag_node(index)
  pointer_list = node + 0xA0
  pine.poke32(node + 0x94, len(parents))
  pine.poke32(node + 0x98, pointer_list)
  for i, parent in enumerate(parents):
    pine.poke32(pointer_list + 4*i, dag_node(parent))


def guard(index: int) -> int:
  return GUARD_BASE + index*GUARD_SIZE


def make_guard_list(
  pine: FakePine, addr: dict, head_index: int, n: int,
  transform: bool = True
) -> list[int]:
  guards = [guard(i) for i in range(n)]
  pine.poke32(addr["guard structs"][head_index], guards[0] if n else 0)
  for i, g in enumerate(guards):
    pine.poke32(g + 0x20, guards[i+1] if i+1 < n else 0)
    if transform:
      pine.poke32(g + 0x54, g + 0x800)
  return guards


def set_active_character(
  pine: FakePine, addr: dict, kind: int = 7, health: int = 100
) -> int:
  pine.poke32(addr["active character"], kind)
  pine.poke32(addr["active character pointer"], CHARACTER)
  pine.poke32(CHARACTER + 0xe00, CHARACTER + 0x2000)
  pine.poke32(CHARACTER + 0x2000, health)
  pine.poke32(CHARACTER + 0x9f0, CHARACTER + 0x3000)
  pine.poke32(CHARACTER + 0x12fc, CHARACTER + 0x2010)
  pine.poke32(CHARACTER + 0x2010, 100)
  name = {7: "Sly", 8: "Bentley", 9: "Murray"}[kind]
  pine.poke32(addr["health"][name], health)
  return CHARACTER


INFOBOX_PAIR = 63


def set_string_table(pine: FakePine, addr: dict, episode: int) -> None:
  """Point the string table entries used by set_text at writable buffers
  and give the infobox string id a pair the client can repoint."""
  pine.poke32(addr["string table"], STRING_TABLE)
  for i, name in enumerate(("right back", "this powerup.")):
    offset = addr["text"][name][episode-1]
    pine.poke32(STRING_TABLE + offset, STRING_BUFFERS + i*0x100)
  pine.poke32(addr["string pair count"], INFOBOX_PAIR + 1)
  pine.poke32(STRING_TABLE + INFOBOX_PAIR*8, INFOBOX_CLIENT_STRING)
  pine.poke32(STRING_TABLE + INFOBOX_PAIR*8 + 4, STRING_BUFFERS + 0x200)


def infobox_pointer(pine: FakePine) -> int:
  """Where the game would read the infobox text from"""
  return pine.peek32(STRING_TABLE + INFOBOX_PAIR*8 + 4)


def string_buffer(pine: FakePine, addr: dict, name: str, episode: int) -> int:
  offset = addr["text"][name][episode-1]
  return pine.peek32(STRING_TABLE + offset)


def set_infobox_pointers(pine: FakePine, addr: dict) -> None:
  pine.poke32(addr["infobox"], INFOBOX)


