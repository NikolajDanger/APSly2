class RecordingContext(Sly2Context):
  def __init__(self) -> None:
    super().__init__(None, None)
    self.sent: list[dict] = []
    self.deaths: list[str] = []

  async def send_msgs(self, msgs: list[Any]) -> None:
    # Keeps the real send_msgs' timing attribution without a socket.
    with self.time_op("send_msgs"):
      self.sent.extend(msgs)

  async def send_death(self, death_text: str = "") -> None:
    self.deaths.append(death_text)

  def sent_cmds(self, cmd: str) -> list[dict]:
    return [m for m in self.sent if m["cmd"] == cmd]


class ClientTestBase(unittest.IsolatedAsyncioTestCase):
  options: dict[str, Any] = {}
  ctx: RecordingContext
  pine: FakePine
  interface: Sly2Interface
  addr: dict

  async def asyncSetUp(self) -> None:
    self.ctx = RecordingContext()
    self.pine = FakePine()
    self.interface = self.ctx.game_interface
    self.interface.pcsx2_interface = self.pine
    self.interface.connect_to_game()
    self.addr = self.interface.addresses

    self.ctx.slot = 1
    self.ctx.team = 0
    self.ctx.slot_info = {
      1: NetworkSlot("Tester", Sly2Context.game, SlotType.player)
    }
    self.ctx.consume_players_package([NetworkPlayer(0, 1, "Tester", "Tester")])
    self.ctx.slot_data = make_slot_data(**self.options)
    self.ctx.reset_world_state()

  async def asyncTearDown(self) -> None:
    self.ctx.exit_event.set()
    task = getattr(self.ctx, "keep_alive_task", None)
    if task is not None:
      task.cancel()
      with suppress(asyncio.CancelledError):
        await task

  @property
  def slot_data(self) -> dict[str, Any]:
    assert self.ctx.slot_data is not None
    return self.ctx.slot_data

  def item(self, name: str, player: int = 1) -> NetworkItem:
    return NetworkItem(item_dict[name].code, -1, player)

  def give(self, *names: str) -> None:
    self.ctx.items_received.extend(self.item(name) for name in names)

  def loc(self, name: str) -> int:
    return location_dict[name].code

  def enter(
    self, episode: int, map_id: int, job: int = 0xffffffff,
    in_hub: Optional[bool] = None
  ) -> None:
    set_location(self.pine, self.addr, episode, map_id, job)
    self.ctx.current_episode = Sly2Episode(episode)
    if in_hub is not None:
      self.ctx.in_hub = in_hub
